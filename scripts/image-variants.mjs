// Writes smaller copies of the site's photos so phones and thumbnails don't download full-size files.
// Run after adding or replacing an image in public/:  node scripts/image-variants.mjs
// Output: public/_img/<width>/<original path> and src/lib/image-variants.ts (read by src/lib/image-loader.ts).
import { readdir, mkdir, rm, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const PUBLIC = "public";
const OUT = path.join(PUBLIC, "_img");
const WIDTHS = [480, 960];
const MAX_WIDTH = 1920; // originals wider than this are scaled down in place
const SKIP = /^(_img|Advizen Logo)\//; // generated copies, favicons and the share image

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

await rm(OUT, { recursive: true, force: true });
const manifest = {};

for await (const file of walk(PUBLIC)) {
  const rel = path.relative(PUBLIC, file).split(path.sep).join("/");
  if (SKIP.test(rel) || !/\.webp$/i.test(rel)) continue;

  let { width } = await sharp(file).metadata();
  if (width > MAX_WIDTH) {
    const buf = await sharp(file).resize({ width: MAX_WIDTH }).webp({ quality: 80 }).toBuffer();
    await writeFile(file, buf);
    width = MAX_WIDTH;
  }

  const made = [];
  for (const w of WIDTHS) {
    if (w >= width * 0.9) continue; // not worth a copy this close to the original
    const dest = path.join(OUT, String(w), rel);
    await mkdir(path.dirname(dest), { recursive: true });
    const info = await sharp(file).resize({ width: w }).webp({ quality: 78 }).toFile(dest);
    const original = (await stat(file)).size;
    if (info.size > original * 0.85) {
      await rm(dest); // barely smaller than the original: not worth a separate request
      continue;
    }
    made.push(w);
  }
  if (made.length) manifest[`/${rel}`] = made;
}

const body = Object.entries(manifest)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `  ${JSON.stringify(k)}: [${v.join(", ")}],`)
  .join("\n");
await writeFile(
  "src/lib/image-variants.ts",
  `// Generated by scripts/image-variants.mjs — do not edit by hand.\n// Widths of the smaller copies in public/_img/<width>/ for each original.\nexport const IMAGE_VARIANTS: Record<string, number[]> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(manifest).length} images with smaller copies`);
