// Writes smaller copies of the site's photos so phones and thumbnails don't download full-size files.
// Run after adding or replacing an image in public/:  node scripts/image-variants.mjs
// Output: public/_img/<width>/<original path> and src/lib/image-variants.ts (read by src/lib/image-loader.ts).
// The manifest also holds a short content hash per photo: the loader adds it to the URL, so a replaced
// photo gets a new address and browsers holding the old one in their 30-day cache fetch it again.
import { readdir, readFile, mkdir, rm, writeFile, stat } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import sharp from "sharp";

const PUBLIC = "public";
const OUT = path.join(PUBLIC, "_img");
const WIDTHS = [480, 960];
const MAX_WIDTH = 1920; // originals wider than this are scaled down in place
const SKIP = /^(_img|Advizen Logo)\//; // generated copies, favicons and the share image

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

await rm(OUT, { recursive: true, force: true });
const manifest = {};
const versions = {};

for await (const file of walk(PUBLIC)) {
  const rel = path.relative(PUBLIC, file).split(path.sep).join("/");
  // Guide PDFs keep their names too: hash them so their links change when a new edition replaces them.
  if (/^guides\/[^/]+\.pdf$/i.test(rel)) {
    versions[`/${rel}`] = createHash("sha256").update(await readFile(file)).digest("hex").slice(0, 8);
    continue;
  }
  if (SKIP.test(rel) || !/\.webp$/i.test(rel)) continue;

  let { width } = await sharp(file).metadata();
  if (width > MAX_WIDTH) {
    const buf = await sharp(file).resize({ width: MAX_WIDTH }).webp({ quality: 80 }).toBuffer();
    await writeFile(file, buf);
    width = MAX_WIDTH;
  }
  versions[`/${rel}`] = createHash("sha256").update(await readFile(file)).digest("hex").slice(0, 8);

  const made = [];
  for (const w of WIDTHS) {
    if (w >= width * 0.9) continue; // not worth a copy this close to the original
    const dest = path.join(OUT, String(w), rel);
    await mkdir(path.dirname(dest), { recursive: true });
    const info = await sharp(file).resize({ width: w }).webp({ quality: 78 }).toFile(dest);
    const original = (await stat(file)).size;
    if (info.size > original * 0.85) {
      await rm(dest); // barely smaller than the original: not worth a separate request
      continue;
    }
    made.push(w);
  }
  if (made.length) manifest[`/${rel}`] = made;
}

const lines = (obj, fmt) =>
  Object.entries(obj)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${fmt(v)},`)
    .join("\n");
await writeFile(
  "src/lib/image-variants.ts",
  `// Generated by scripts/image-variants.mjs — do not edit by hand.\n` +
    `// Widths of the smaller copies in public/_img/<width>/ for each original.\n` +
    `export const IMAGE_VARIANTS: Record<string, number[]> = {\n${lines(manifest, (v) => `[${v.join(", ")}]`)}\n};\n\n` +
    `// Content hash of each original photo and guide PDF, added to its URLs so a replaced file is not served from cache.\n` +
    `export const IMAGE_VERSIONS: Record<string, string> = {\n${lines(versions, JSON.stringify)}\n};\n`,
);
console.log(`${Object.keys(manifest).length} images with smaller copies`);
